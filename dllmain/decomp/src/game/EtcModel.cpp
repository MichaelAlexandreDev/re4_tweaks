// Etc id of slot `no`; 0x68 (none) with an error for an empty slot.
// FUNCTION: BIO4 0x006179E0
// STATUS: matching
static int getRoomEtcID(int no)
{
    cEtcTbl* t = &g_EtcTbl[no];

    if (t->stat != 1) {
        pLog->err(6, 0, "getRoomEtcID() : No[%d] not Initialized.", no);
        return ETC_ID_MAX;   // 0x6A on PC (two more ids)
    }
    return t->pData->id;
}

// Data of file `name` in an etc archive (linear search of the file headers); NULL with an error
// when missing.
// FUNCTION: BIO4 0x00617A20
// STATUS: matching
void* GetEtcAddr(void* arc, const char* name)
{
    EtcArc* a = (EtcArc*) arc;
    EtcArcFile* f = a->file;
    u32 i;

    for (i = 0; i < a->num; i++) {
        if (strcmp(f->name, name) == 0) {
            return f->data;
        }
        f = (EtcArcFile*) ((u8*) f + f->size);
    }
    pLog->err(6, 0, "GetEtcAddr() : [%s] not found.", name);
    return 0;
}

// Boot: clears the 64 slots, the per-id archive table and the list bookkeeping.
// FUNCTION: BIO4 0x00617AC0
// STATUS: matching
void EtcModelInit()
{
    int i;
    u32 j;
    cEtcTbl* p = g_EtcTbl;

    for (i = 0; i < 0x40; i++, p++) {
        p->Init();
    }
    for (j = 0; j < 0x6A; j++) {
        g_Etc_das_addr[j] = 0;
    }
    g_LastNo = 0;
    g_addr = 0;
}

