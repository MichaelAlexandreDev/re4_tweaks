// Ambient table of the current room. The PC adds the Separate Ways rooms
// (0x5xx) to the GameCube tests.
// FUNCTION: BIO4 0x0061D720
// STATUS: matching
ETC_AMB_TYPE GetEtcAmbType()
{
    if (pG->room_id == 0x400 || pG->room_id == 0x403) {
        return ETC_AMB_DAY;
    } else if (pG->room_id == 0x402) {
        return ETC_AMB_DAY3;
    } else if (pG->room_id >= 0x404 && pG->room_id <= 0x411) {
        return ETC_AMB_NIGHT;
    } else if (pG->room_id == 0x331) {
        return ETC_AMB_DAY2;
    } else if (pG->room_id == 0x108 || pG->room_id == 0x502) {
        return ETC_AMB_NIGHT;
    } else if (pG->room_id == 0x106 || pG->room_id == 0x507) {
        return ETC_AMB_DAY4;
    } else if (pG->room_id == 0x102 || pG->room_id == 0x109 || pG->room_id == 0x119 || pG->room_id == 0x10A ||
               pG->room_id == 0x10B || pG->room_id == 0x327 || pG->room_id == 0x30F || pG->room_id == 0x334 ||
               pG->room_id == 0x31D || pG->room_id == 0x501) {
        return ETC_AMB_DAY2;
    } else if (pG->room_id >= 0x100 && pG->room_id <= 0x10B) {
        return ETC_AMB_DAY;
    } else if (pG->room_id >= 0x10C && pG->room_id <= 0x11E) {
        return ETC_AMB_NIGHT;
    } else if (pG->room_id == 0x509 || pG->room_id == 0x503 || pG->room_id == 0x508 || pG->room_id == 0x50A) {
        return ETC_AMB_NIGHT;
    } else if (pG->room_id >= 0x200 && pG->room_id <= 0x22A) {
        return ETC_AMB_DAY3;
    } else if (pG->room_id >= 0x50C && pG->room_id <= 0x510) {
        return ETC_AMB_DAY3;
    } else if (pG->room_id >= 0x300) {
        return ETC_AMB_NIGHT;
    }
    return (ETC_AMB_TYPE) (pG->room_id >= 0x511);
}

// 1 when the ganados' glowing eye effect may be shown in the current room (off in the bright
// village rooms 102 / 106 / 108 / 109 / 10A / 119; PC: also off in 0x50C..0x510, on from 0x508).
// FUNCTION: BIO4 0x0061D950
// STATUS: matching
int GetEm10EyeEffectEnable()
{
    if (pG->room_id == 0x108 || pG->room_id == 0x106 || pG->room_id == 0x102 || pG->room_id == 0x109 ||
        pG->room_id == 0x119 || pG->room_id == 0x10A || pG->room_id == 0x10B) {
        return 0;
    } else if (pG->room_id >= 0x100 && pG->room_id <= 0x10B) {
        return 0;
    } else if (pG->room_id >= 0x10C && pG->room_id <= 0x11E) {
        return 1;
    } else if (pG->room_id >= 0x200 && pG->room_id <= 0x22A) {
        return 0;
    } else if (pG->room_id >= 0x300 && pG->room_id < 0x500) {
        return 1;
    } else if (pG->room_id >= 0x50C && pG->room_id <= 0x510) {
        return 0;
    }
    return pG->room_id >= 0x508;
}

// Applies the room's additive ambient colour for etc ambient kind `no` (the etc classes pass
// their kind) from the day / night / variant tables chosen by the room id (GetEtcAmbType).
// FUNCTION: BIO4 0x0061DA60
// STATUS: matching
void EtcSetAddAmb(cModel* pMod, int kind)
{
    u8 r = 0;
    u8 g = 0;
    u8 b = 0;

    switch (GetEtcAmbType()) {
    case ETC_AMB_DAY:
        r = etc_day_rgb[kind].r;
        g = etc_day_rgb[kind].g;
        b = etc_day_rgb[kind].b;
        break;
    case ETC_AMB_NIGHT:
        r = etc_night_rgb[kind].r;
        g = etc_night_rgb[kind].g;
        b = etc_night_rgb[kind].b;
        break;
    case ETC_AMB_DAY2:
        r = etc_day2_rgb[kind].r;
        g = etc_day2_rgb[kind].g;
        b = etc_day2_rgb[kind].b;
        break;
    case ETC_AMB_DAY3:
        r = etc_day3_rgb[kind].r;
        g = etc_day3_rgb[kind].g;
        b = etc_day3_rgb[kind].b;
        break;
    case ETC_AMB_DAY4:
        r = etc_day4_rgb[kind].r;
        g = etc_day4_rgb[kind].g;
        b = etc_day4_rgb[kind].b;
        break;
    default:
        pLog->err(6, 0, "EtcSetAddAmb() : invalid type.");
        break;
    }
    if (r == 0 && g == 0 && b == 0) {
        pMod->be_flag &= ~8;
    } else {
        pMod->be_flag |= 8;
    }
    pMod->AddAmb_r = r;
    pMod->AddAmb_g = g;
    pMod->AddAmb_b = b;
}
