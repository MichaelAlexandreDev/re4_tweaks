// Tune type pick for the chosen weapon: shows its level table and the type's description message
// (0xF + lvType; the Mine Thrower's special text); B (or nothing tunable) back to the list, A on a
// tunable type computes the price (type 4 = every type at once) and opens LvUpConfirm; up/down
// move lvType over the available rows.
// FUNCTION: BIO4 0x00796DA0
// STATUS: stub
// PC: nibble order fire, speed, reload, capacity; leaving only beeps when the weapon is tunable;
// the minus key also leaves.
void LvUpItemSelect::move(SUB_SCREEN* wk)
{
    ShopWork* sw = wk->shop;
    Merchant* m = wk->merchant;
    ItemWork* item = m->levelupItemPtr(sw->cursor);
    IdUnit* u;
    int x;
    int y;
    int i;

    weaponLevelDisp(item, item->id, 1, 1);
    levelItemDisp(wk, 1);
    u = IdSub.unitPtr(0xFC, IDC_SSCRN_CKPT_0);
    x = (int) ((u->pos0.x + 320.0) * 0.8f);
    y = (int) ((240.0 - u->pos0.y) * 0.8f);
    cMes.setLayout(1, LAYOUT_SUBSCRN);
    if (sw->lvType == 4) {
        cMes.MesSet(specialCaption(item->id), x, y, 0x20081, 1, 0, 3);
    } else {
        int no = sw->lvType + 0xF;
        if (item->id == 0x36 && sw->lvType == 0) {
            no = 0x38;
        }
        cMes.MesSet(no, x, y, 0x20081, 1, 0, 3);
    }
    if ((Key.trg & (KEY_CANCEL | KEY_MINUS)) || !m->tunable(item)) {
        transit(1, wk);
        if (m->tunable(item) == 1) {
            SndCall(0, 5, 0, 0, 0, 0);
        }
        return;
    }
    if (Key.trg & KEY_OK) {
        int lv = 0;

        if (m->specialTunable(sw->item)) {
            if (sw->lvType != 4) {
                return;
            }
            sw->price = 0;
            for (lv = 0; lv < 4; lv++) {
                int mx = m->levelMax(item->id, lv);
                if (mx > WeaponId2MaxLevel(item->id, lv)) {
                    sw->price += m->levelupPrice(sw->item, lv, mx);
                }
            }
        } else {
            int mx;

            switch (sw->lvType) {
            case 0:
                lv = (s8) ((item->lv8[0] & 0xF) + 1);
                break;
            case 1:
                lv = (s8) (((item->lv8[0] >> 4) & 0xF) + 1);
                break;
            case 2:
                lv = (s8) ((item->lv8[1] & 0xF) + 1);
                break;
            case 3:
                lv = (s8) (((item->lv >> 12) & 0xF) + 1);
                break;
            }
            lv++;
            mx = m->levelMax(item->id, sw->lvType);
            sw->price = m->levelupPrice(sw->item, sw->lvType, lv);
            if (lv > WeaponId2MaxLevel(item->id, sw->lvType) || lv > mx) {
                return;
            }
        }
        transit(0, wk);
        return;
    }
    {
        int old = sw->lvType;

        if (Key.rep & KEY_U) {
            sw->lvType = old - 1;
        }
        if (Key.rep & KEY_D) {
            sw->lvType++;
        }
        if (m->specialTunable(sw->item) == 1) {
            sw->lvType = sw->lvType < 0 ? 0 : (sw->lvType > 4 ? 4 : sw->lvType);
        } else {
            sw->lvType = sw->lvType < 0 ? 0 : (sw->lvType > 3 ? 3 : sw->lvType);
        }
        if (old != sw->lvType) {
            SndCall(0, 6, 0, 0, 0, 0);
        }
    }
    for (i = 0; i < 5; i++) {
        IdUnit* frame = IdSub.unitPtr(0x40 + i, IDC_SSCRN_CKPT_1);
        if (i == sw->lvType) {
            IdSub.unitPtr(0x3F, IDC_SSCRN_CKPT_1)->pos0 = frame->pos0;
        }
    }
    for (i = 0; i < 4; i++) {
        IdSub.unitPtr(0x21 + i, IDC_SSCRN_CKPT_0)->be_flag &= ~8;
    }
    if (sw->lvType != 4) {
        IdSub.unitPtr((u8) sw->lvType + 0x21, IDC_SSCRN_CKPT_0)->be_flag |= 8;
    }
}

// Tune confirm open: current levels (cur[]) and the merchant's maxima (max[]); message 0x17 (buy?)
// with the price, or the "cannot afford" / "already max" lines.
// FUNCTION: BIO4 0x00790D50
// STATUS: matching
// PC: the tune levels are packed fire | speed << 4 | reload << 8 | capacity << 12; message x
// relative to shop_msg_x, language-dependent attribute; the confirm frame stays.
void LvUpConfirm::init(SUB_SCREEN* wk)
{
    ShopWork* sw = wk->shop;
    Merchant* m = wk->merchant;
    IdUnit* u;
    int x;
    int y;

    cur[0] = (sw->item->lv8[0] & 0xF) + 1;
    cur[1] = sw->item->tune.speed + 1;
    cur[2] = (sw->item->lv8[1] & 0xF) + 1;
    cur[3] = ((sw->item->lv >> 12) & 0xF) + 1;
    max[0] = m->levelMax(sw->item->id, 0);
    max[1] = m->levelMax(sw->item->id, 1);
    max[2] = m->levelMax(sw->item->id, 2);
    max[3] = m->levelMax(sw->item->id, 3);
    sw->lv[0] = cur[0];
    sw->lv[1] = cur[1];
    sw->lv[2] = cur[2];
    sw->lv[3] = cur[3];
    if (m->specialTunable(sw->item) == 1) {
        sw->lv[0] = max[0];
        sw->lv[1] = max[1];
        sw->lv[2] = max[2];
        sw->lv[3] = max[3];
    } else {
        sw->lv[sw->lvType] = cur[sw->lvType] + 1;
    }
    if (sw->price <= *PG_PESETA(pG)) {
        msg = 0x17;
        SndCall(0, 9, 0, 0, 0, 0);
    } else {
        msg = 0x18;
        SndCall(0, 0x19, 0, 0, 0, 0);
    }
    u = IdSub.unitPtr(0xFC, IDC_SSCRN_CKPT_0);
    y = (int) ((240.0 - u->pos0.y) * 0.8f);
    x = shop_msg_x - (int) ((u->pos0.x + 320.0) * -0.8f);
    if (pSys->language == 1) {
        cMes.MesSet(shop_msg[msg].msg, x, y, 0x20801, 1, 0, 3);
    } else {
        cMes.MesSet(shop_msg[msg].msg, x, y, 0x20841, 1, 0, 3);
    }
    shopStrPlay(wk, shop_msg[msg].str);
}

// Tune confirm: yes applies the levels (Merchant::levelup / ItemMgr, pesetas paid, sw->lv[]
// stored) with the thanks line, no / B back to the type pick.
// FUNCTION: BIO4 0x00797680
// STATUS: stub
// PC: tune nibbles fire | speed << 4 | reload << 8 | capacity << 12; a capacity tune-up of the
// equipped weapon refreshes the player's weapon object; the minus key also cancels.
void LvUpConfirm::move(SUB_SCREEN* wk)
{
    ShopWork* sw = wk->shop;

    levelItemDisp(wk, 1);
    if (Key.trg & (KEY_CANCEL | KEY_MINUS)) {
        cMes.Delete(1);
        transit(0, wk);
        SndCall(0, 5, 0, 0, 0, 0);
        return;
    }
    if (msg == 0x17) {
        result = cMes.getMes(1)->m_sel;
        if (result == 0) {
            return;
        }
        switch (result) {
        case 1:
            sw->item->tune.fire = (s8) sw->lv[0] - 1;
            sw->item->tune.speed = (s8) sw->lv[1] - 1;
            sw->item->tune.reload = (s8) sw->lv[2] - 1;
            sw->item->tune.cap = (s8) sw->lv[3] - 1;
            if (sw->lvType == 3 || sw->lvType == 4) {
                ItemWork* item = sw->item;

                item->ammo.bullet = WeaponId2ChargeNum(item->id, (s8) (item->tune.cap + 1));
                if (item->id == ItemMgr.m_wep_id) {
                    PL_WEP(pPL)->obj->bulletUpdate(0);
                }
            }
            if (ItemMgr.pArm == sw->item) {
                ItemMgr.arm(sw->item);
            }
            *PG_PESETA(pG) -= sw->price;
            shopStrPlay(wk, shop_msg[25].str);
            SndCall(0, 0x18, 0, 0, 0, 0);
            break;
        case 2:
            SndCall(0, 5, 0, 0, 0, 0);
            break;
        }
        transit(0, wk);
    } else if (msg == 0x18) {
        if (Key.trg & KEY_OK) {
            cMes.Delete(1);
            transit(0, wk);
            SndCall(0, 5, 0, 0, 0, 0);
        }
    }
}

