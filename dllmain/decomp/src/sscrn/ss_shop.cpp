// Tune-up list: B closes the coat and returns to the top menu; A picks the weapon (sw->item ->
// LvUpItemSelect), up/down move the cursor.
// FUNCTION: BIO4 0x00799B50
// STATUS: stub
// PC: the caption shows the owned weapon (shopListItemId); the minus key also leaves.
void LvUpMenuSelect::move(SUB_SCREEN* wk)
{
    ShopWork* sw = wk->shop;
    Merchant* m = wk->merchant;
    ItemWork* item;

    moveItem();
    item = m->levelupItemPtr(sw->cursor);
    if (item) {
        itemCaption(shopListItemId(item));
    } else {
        itemCaption(m->levelupItemNo(sw->cursor)->id);
    }
    dispLvUpItemList(wk, 5, state != 0);
    if (Key.trg & (KEY_CANCEL | KEY_MINUS)) {
        transit(1, wk);
        closeCoat(wk);
        SndCall(0, 5, 0, 0, 0, 0);
        return;
    }
    switch (state) {
    case 0:
        if (IdSub.unitPtr(0xFA, IDC_SSCRN_CKPT_1)->anima_state & 1) {
            state = 1;
        }
        break;
    case 1:
        if (Key.trg & KEY_OK) {
            sw->item = m->levelupItemPtr(sw->cursor);
            if (sw->item && m->tunable(sw->item)) {
                if (m->specialTunable(sw->item)) {
                    sw->lvType = 4;
                } else {
                    sw->lvType = 0;
                }
                transit(0, wk);
                SndCall(0, 4, 0, 0, 0, 0);
                break;
            }
        }
        {
            int old = sw->cursor;

            if (Key.rep & KEY_U) {
                sw->cursor = old - 1;
            }
            if (Key.rep & KEY_D) {
                sw->cursor++;
            }
            {
                int c = sw->cursor;
                if (c >= 0) {
                    if (c > sw->num - 1) {
                        c = sw->num - 1;
                    }
                } else {
                    c = 0;
                }
                sw->cursor = c;
            }
            if (old != sw->cursor) {
                SndCall(0, 6, 0, 0, 0, 0);
            }
            if (sw->cursor > sw->top + 4) {
                sw->top = sw->cursor - 4;
            }
            if (sw->cursor < sw->top) {
                sw->top = sw->cursor;
            }
            if (old != sw->cursor) {
                dispItem(m->levelupItemNo(sw->cursor)->id, 1);
            }
        }
        break;
    }
}

