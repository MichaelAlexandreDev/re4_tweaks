// Sell count: draws the count and total buy-up price digits; B back, A opens the confirm message
// (shop_msg 6, or 7 "a valuable one" for expensive items; count 0 cancels), up/down change the
// count (held stick steps faster, wraps 1 <-> max).
// FUNCTION: BIO4 0x00795F60
// STATUS: stub
// PC: the confirm message position is relative to shop_msg_x/y, a single price threshold (10000),
// the language-dependent message attribute; the minus key also cancels.
void SellItemNum::move(SUB_SCREEN* wk)
{
    ShopWork* sw = wk->shop;
    Merchant* m = wk->merchant;
    IdUnit* u;
    int k;
    int val;
    u8 n;
    u8 base;
    int max;

    dispSellItemList(wk, 5, 1);
    u = IdSub.unitPtr(0xFC, IDC_SSCRN_CKPT_0);
    {
        int x = (int) ((u->pos0.x + 320.0) * 0.8f);
        int y = (int) ((240.0 - u->pos0.y) * 0.8f);

        cMes.setLayout(0, LAYOUT_SUBSCRN);
        cMes.MesSet(sw->item->id, x, y, 0x20088, 0, 0, 5);
    }
    n = 0;
    base = 0;
    u = IdSub.unitPtr(0, IDC_SSCRN_CKPT_3);
    u->be_flag |= 8;
    u->pos0 = sell_num_pos;
    for (k = 0; k < 2; k++) {
        int digit[10];
        int on;
        int i;

        switch (k) {
        case 0:
            val = sw->count;
            n = 4;
            base = 1;
            break;
        case 1:
            n = 7;
            val = m->buyupPrice(sw->item, sw->count);
            base = 0x11;
            break;
        }
        for (i = 0; i < n; i++) {
            digit[i] = val % 10;
            val /= 10;
            IdSub.unitPtr(base + i, IDC_SSCRN_CKPT_3)->be_flag &= ~8;
        }
        on = 0;
        for (i = n - 1; i >= 0; i--) {
            if (on == 0) {
                if (digit[i] == 0 && i != 0) {
                    continue;
                }
                on = 1;
            }
            u = IdSub.unitPtr(base + i, IDC_SSCRN_CKPT_3);
            u->be_flag |= 8;
            u->tex_flag |= 2;
            u->texNo = digit[i];
        }
    }
    {
        ItemInfo info;
        itemInfo(sw->item->id, &info);
        if (info.type == 1) {
            max = 1;
        } else {
            max = ItemMgr.num(sw->item->id);
        }
    }
    if (Key.trg & (KEY_CANCEL | KEY_MINUS)) {
        IdSub.unitPtr(0, IDC_SSCRN_CKPT_3)->be_flag &= ~8;
        transit(1, wk);
        SndCall(0, 5, 0, 0, 0, 0);
    } else if (Key.trg & KEY_OK) {
        if (sw->count == 0) {
            IdSub.unitPtr(0, IDC_SSCRN_CKPT_3)->be_flag &= ~8;
            transit(1, wk);
            SndCall(0, 5, 0, 0, 0, 0);
        } else {
            int msg = 6;
            int x;
            int y;

            if (m->buyupPrice(sw->item, 1) >= 10000) {
                msg = 7;
            }
            u = IdSub.unitPtr(0xFC, IDC_SSCRN_CKPT_0);
            x = shop_msg_x - (int) ((u->pos0.x + 320.0) * -0.8f);
            y = shop_msg_y - (int) ((240.0 - u->pos0.y) * -0.8f);
            if (pSys->language == 1) {
                cMes.MesSet(shop_msg[msg].msg, x, y, 0x20801, 1, 0, 3);
            } else {
                cMes.MesSet(shop_msg[msg].msg, x, y, 0x20841, 1, 0, 3);
            }
            cMes.getMes(1)->m_cur = 1;
            transit(0, wk);
            SndCall(0, 9, 0, 0, 0, 0);
            shopStrPlay(wk, shop_msg[msg].str);
        }
    } else {
        int old = sw->count;

        if (old == 1 && (Key.trg & KEY_D)) {
            sw->count = max;
        } else if (sw->count == max && (Key.trg & KEY_U)) {
            sw->count = 1;
        } else {
            int step;

            if (Key.on & (KEY_U | KEY_D)) {
                repeat++;
                if (repeat > 30) {
                    repeat = 30;
                    fast = 1;
                } else {
                    fast = 0;
                }
            } else {
                repeat = 0;
                fast = 0;
            }
            step = fast ? 8 : 1;
            if (Key.rep & KEY_D) {
                sw->count -= step;
            } else if (Key.rep & KEY_U) {
                sw->count += step;
            }
            {
                int c = sw->count;
                if (c < 1) {
                    c = 1;
                } else if (c > max) {
                    c = max;
                }
                sw->count = c;
            }
        }
        if (old != sw->count) {
            SndCall(0, 0xA, 0, 0, 0, 0);
        }
    }
}

// Sell yes/no: yes sells `count` of the item (Merchant::buyup adds pesetas, the items are dumped,
// the armed weapon unequipped if gone), rebuilds the case and plays the thanks line; B or no
// returns to the list.
// FUNCTION: BIO4 0x00796560
// STATUS: matching
// PC: the minus key also cancels; message attribute / language layout as SellItemNum::move.
