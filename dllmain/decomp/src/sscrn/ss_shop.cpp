// Picks the merchant's greeting lines (shop_msg indices into `tbl`): the first ever visit (Scenario
// bit 22 set here) gets 0 + 2, the first visit of a session (Status_flg[2] bit 18) gets "new stock"
// (1) or the plain greeting (0) plus the village hints 3/4; 0 when nothing is to be said.
// FUNCTION: BIO4 0x007902D0
// STATUS: stub
// Static: num arrives in ESI, tbl in EDI. PC: Separate Ways greetings (0x1B first, then 0x1C);
// rooms 0x104 / 0x102 have a one-time line 0x1A; the "come again" hint 2 only before a clear.
static bool getGreetMsg(int* num, int* tbl)
{
    Merchant* m = SubScreenWk.merchant;

    if (pG->System_flg & SYS_PS2_ADA_GAME) {
        *num = 0;
        if (pG->Status_flg[2] & 0x40000) {
            return false;
        }
        pG->Status_flg[2] |= 0x40000;
        if (!(PG_SCF(pG)[2] & 8)) {
            PG_SCF(pG)[2] |= 8;
            tbl[(*num)++] = 0x1B;
            return true;
        }
        tbl[(*num)++] = 0x1C;
        return true;
    }
    if (!(PG_SCF(pG)[1] & 0x400000)) {
        PG_SCF(pG)[1] |= 0x400000;
        pG->Status_flg[2] |= 0x40000;
        *num = 0;
        if (pG->room_id == 0x104 && !(PG_SCF(pG)[1] & 0x20000000)) {
            PG_SCF(pG)[1] |= 0x20000000;
            tbl[*num] = 0x1A;
        } else if (pG->room_id == 0x102 && !(PG_SCF(pG)[5] & 0x40)) {
            PG_SCF(pG)[5] |= 0x40;
            tbl[*num] = 0x1A;
        } else if (m->stockNew() || m->levelNew()) {
            tbl[*num] = 1;
        } else {
            tbl[*num] = 0;
        }
        (*num)++;
        if (PG_GAME_CNT(pG) == 0) {
            tbl[(*num)++] = 2;
        }
        return true;
    }
    if (pG->Status_flg[2] & 0x40000) {
        return false;
    }
    pG->Status_flg[2] |= 0x40000;
    *num = 0;
    if (pG->room_id == 0x104 && !(PG_SCF(pG)[1] & 0x20000000)) {
        ScenarioFlagOn(0x22);
        tbl[*num] = 0x1A;
    } else if (pG->room_id == 0x102 && !(PG_SCF(pG)[5] & 0x40)) {
        ScenarioFlagOn(0xB9);
        tbl[*num] = 0x1A;
    } else if (m->stockNew() || m->levelNew()) {
        tbl[*num] = 1;
    } else {
        tbl[*num] = 0;
    }
    (*num)++;
    if (pG->stage_no == 1) {
        if (!(PG_SCF(pG)[0] & 0x40000)) {
            if (!ScenarioFlagChk(0x27) && PG_GAME_CNT(pG) == 0) {
                tbl[(*num)++] = 3;
            }
        } else if (!ItemFlagChk(3)) {
            tbl[(*num)++] = 4;
        }
    }
    return true;
}

