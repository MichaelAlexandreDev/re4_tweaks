                case 2:
                    val[0] = (int) (getReloadRatio(id, lv - 1) * 100.0f + 0.5f);
                    val[1] = (int) (getReloadRatio(id, lv) * 100.0f + 0.5f);
                    tag[0] = 'a';
                    tag[1] = 'd';
